
def area(a):
    '''Вычисляет площадь квадрата по длине его стороны
        Параметр:
          a (float): длина стороны квадрата
        Возвращаемое значение:
          float: площадь квадрата
        Пример вызова:
          square area(8)
    '''
    return a * a


def perimeter(a):
    '''Вычисляет периметр квадрата по длине его стороны
        Параметр:
          a (float): длина стороны квадрата
        Возвращаемое значение:
          float: периметр квадрата
        Пример вызова:
          square perimeter(8)
    '''
    return 4 * a
